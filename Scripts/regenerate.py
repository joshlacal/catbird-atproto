#!/usr/bin/env python3
"""Project the shared core/overlay corpus through mls-codegen reproducibly.

Checkpoint this repository with jj before `generate`. The `check` action writes
only to temporary staging and verifies the complete committed generated tree.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def fingerprint(root):
    return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file()}


def normalize_projection(stage, overlay):
    normalize_named_byte_fields(stage)
    # Namespace feature gates belong to the reproducible projection rather than
    # one-off edits to the generated module index.
    index = stage / "com_atproto.rs"
    text = index.read_text()
    for namespace in ["space", "simplespace"]:
        marker = f"pub mod {namespace};"
        if text.count(marker) != 1:
            raise ValueError(f"Expected one generated {namespace} module")
        text = text.replace(marker, '#[cfg(feature = "namespace-atproto-space")]\n' + marker)
    index.write_text(text)

    # Jacquard's JSON default codec cannot decode a schema-less relayed JSON body
    # into its generated Bytes wrapper. Preserve the actual raw-body contract.
    schema = json.loads((overlay / "blue/catbird/labyrinth/blue.catbird.labyrinth.labyrinthRelay.json").read_text())
    output = schema["defs"]["main"]["output"]
    if output.get("encoding") != "application/json" or "schema" in output:
        raise ValueError("Review the relay projection when its output schema changes")
    relay = stage / "blue_catbird/labyrinth/labyrinth_relay.rs"
    text = relay.read_text()
    marker = "    type Err = LabyrinthRelayError;"
    if text.count(marker) != 1 or "fn decode_output" in text:
        raise ValueError("Review the relay projection after a Jacquard codec change")
    text = text.replace(marker, marker + '''
    fn encode_output<S: jacquard_common::BosStr>(
        output: &Self::Output<S>,
    ) -> Result<Vec<u8>, jacquard_common::xrpc::EncodeError>
    where
        Self::Output<S>: serde::Serialize,
    {
        Ok(output.body.to_vec())
    }
    fn decode_output<'de, S>(
        body: &'de [u8],
    ) -> Result<Self::Output<S>, jacquard_common::error::DecodeError>
    where
        S: jacquard_common::BosStr + serde::Deserialize<'de>,
        Self::Output<S>: serde::Deserialize<'de>,
    {
        Ok(LabyrinthRelayOutput {
            body: jacquard_common::deps::bytes::Bytes::copy_from_slice(body),
        })
    }
''')
    relay.write_text(text)


def normalize_named_byte_fields(stage):
    """Carry the bytes codec across Jacquard's transparent named aliases.

    Jacquard 0.13 annotates inline bytes but drops that annotation for refs to
    named bytes definitions. Without it JSON `$bytes` maps cannot decode and
    DAG-CBOR serializes the alias as an integer array instead of a byte string.
    Discover aliases from generated definitions so the fix follows the schema
    corpus and does not depend on private field/type names.
    """
    files = sorted(stage.rglob("*.rs"))
    aliases = set()
    for path in files:
        module = "::".join(path.relative_to(stage).with_suffix("").parts)
        for name in re.findall(
            r"pub type (\w+) = jacquard_common::deps::bytes::Bytes;", path.read_text()
        ):
            aliases.add(f"crate::generated::{module}::{name}")
    if not aliases:
        raise ValueError("Review named-byte projection after a Jacquard type change")

    field_pattern = re.compile(r"(?m)^(    )pub (\w+): ([^,]+),$")
    count = 0
    for path in files:
        text = path.read_text()

        def annotate(match):
            nonlocal count
            field_type = "".join(match[3].split())
            if field_type in aliases:
                helper = 'with = "jacquard_common::serde_bytes_helper"'
            elif any(field_type == f"core::option::Option<{alias}>" for alias in aliases):
                helper = 'default, with = "jacquard_common::opt_serde_bytes_helper"'
            elif any(alias in field_type for alias in aliases):
                raise ValueError(f"Unsupported named-byte field shape in {path}: {field_type}")
            else:
                return match[0]
            # Fail if upstream starts providing its own codec; do not silently
            # stack conflicting serde attributes on an upgraded generator.
            attributes = text[max(0, text.rfind("\n    pub ", 0, match.start())):match.start()]
            if "serde_bytes_helper" in attributes:
                # Only the contiguous attributes on this field are relevant.
                last_field_end = attributes.rfind(",\n")
                if "serde_bytes_helper" in attributes[last_field_end + 2:]:
                    raise ValueError(f"Review upstream byte codec for {path}:{match[2]}")
            count += 1
            return f"{match[1]}#[serde({helper})]\n{match[0]}"

        updated = field_pattern.sub(annotate, text)
        if updated != text:
            path.write_text(updated)
    print(f"Preserved bytes codec on {count} named byte fields")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["generate", "check"])
    parser.add_argument("--generator", required=True, type=Path, help="Built mls-codegen gen-lexicons executable")
    parser.add_argument("--core-lexicons", type=Path, default=ROOT.parent / "Petrel/generator/lexicons")
    parser.add_argument("--overlay-lexicons", type=Path, default=ROOT.parent / "PetrelCatbird/lexicons")
    args = parser.parse_args()
    staging = Path(tempfile.mkdtemp(prefix="catbird-atproto-codegen-"))
    stage = staging / "generated"
    subprocess.run([str(args.generator.resolve()), "--lexdir", str(args.core_lexicons),
                    "--lexdir", str(args.overlay_lexicons), "--outdir", str(stage)], check=True)
    normalize_projection(stage, args.overlay_lexicons)
    paths = sorted(stage.rglob("*.rs"))
    for offset in range(0, len(paths), 80):
        subprocess.run(["rustfmt", "--edition", "2021", *map(str, paths[offset:offset + 80])], check=True)
    target = ROOT / "src/generated"
    if args.action == "check":
        expected, actual = fingerprint(stage), fingerprint(target)
        if expected != actual:
            changed = sorted(name for name in expected.keys() | actual.keys()
                             if expected.get(name) != actual.get(name))
            raise SystemExit(f"Generated projection differs: {changed}")
        print(f"Roundtrip verified: {len(expected)} generated files")
    else:
        if target.exists():
            shutil.move(str(target), str(staging / "previous"))
        shutil.move(str(stage), str(target))
        print(f"Generated {len(paths)} Rust files; previous tree retained at {staging / 'previous'}")


if __name__ == "__main__":
    main()
